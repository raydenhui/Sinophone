<#
.SYNOPSIS
    Regenerates the simplified/traditional conversion tables the plugin embeds.

.DESCRIPTION
    Downloads OpenCC's character and phrase dictionaries for a pinned tag, merges them
    into one table per direction, and writes src/Sinophone/Resources/Conversion. The
    plugin loads the tables from there when the user turns conversion on.

    OpenCC is Apache-2.0. See THIRD-PARTY-NOTICES.md.

    Safe to run more than once: downloaded files are reused and the output files are
    overwritten with the same content for the same tag.

.PARAMETER OutputDirectory
    Where to write s2t.txt.gz and t2s.txt.gz. Defaults to the plugin resource folder.

.PARAMETER DownloadDirectory
    Where to keep the OpenCC files. Defaults to a folder under the system temp path.

.PARAMETER OpenCcTag
    OpenCC git tag to read the dictionaries from.

.EXAMPLE
    pwsh -File scripts/New-ConversionData.ps1
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$OutputDirectory = (Join-Path (Split-Path -Parent $PSScriptRoot) 'src/Sinophone/Resources/Conversion'),
    [string]$DownloadDirectory = (Join-Path ([System.IO.Path]::GetTempPath()) 'sinophone-opencc'),
    [string]$OpenCcTag = 'ver.1.4.2'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$baseUrl = "https://raw.githubusercontent.com/BYVoid/OpenCC/$OpenCcTag/data/dictionary"
$directions = @(
    @{ Name = 's2t'; Files = @('STCharacters', 'STPhrases') }
    @{ Name = 't2s'; Files = @('TSCharacters', 'TSPhrases') }
)
$variantFile = 'TWVariants'

New-Item -ItemType Directory -Path $DownloadDirectory -Force | Out-Null

$sources = @{}
foreach ($file in @($directions.Files) + $variantFile) {
    $path = Join-Path $DownloadDirectory "$file.txt"
    if (-not (Test-Path -LiteralPath $path)) {
        Write-Host "Downloading $file.txt from OpenCC $OpenCcTag"
        Invoke-WebRequest -Uri "$baseUrl/$file.txt" -OutFile $path
    }

    $sources[$file] = $path
}

# The TC game data uses Taiwan forms: 為 not 爲, 裡 not 裏, 才 not 纔. OpenCC's
# base s2t table keeps the older variants, so map each s2t value through its
# Taiwan table, the same step the s2tw config takes.
$variants = [System.Collections.Generic.Dictionary[char, char]]::new()
foreach ($line in [System.IO.File]::ReadLines($sources[$variantFile])) {
    if ($line.Length -eq 0 -or $line[0] -eq [char]'#') { continue }

    $parts = $line.Split([char]"`t", 2)
    if ($parts.Length -ne 2 -or $parts[0].Length -ne 1) { continue }

    $variants[$parts[0][0]] = $parts[1][0]
}

if (-not $PSCmdlet.ShouldProcess($OutputDirectory, 'Write the conversion tables')) {
    return
}

New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null

foreach ($direction in $directions) {
    # Phrases are applied last because they are more specific than single characters.
    $table = [System.Collections.Generic.Dictionary[string, string]]::new([System.StringComparer]::Ordinal)

    foreach ($file in $direction.Files) {
        foreach ($line in [System.IO.File]::ReadLines($sources[$file])) {
            if ($line.Length -eq 0 -or $line[0] -eq [char]'#') { continue }

            $parts = $line.Split([char]"`t", 2)
            if ($parts.Length -ne 2 -or $parts[0].Length -eq 0) { continue }

            # OpenCC lists candidates in preference order; the plugin keeps one.
            $value = $parts[1].Split([char]' ')[0]
            if ($value.Length -eq 0) { continue }

            $table[$parts[0]] = $value
        }
    }

    if ($direction.Name -eq 's2t') {
        foreach ($key in @($table.Keys)) {
            $chars = $table[$key].ToCharArray()
            for ($i = 0; $i -lt $chars.Length; $i++) {
                if ($variants.ContainsKey($chars[$i])) { $chars[$i] = $variants[$chars[$i]] }
            }

            $table[$key] = [string]::new($chars)
        }
    }

    $keys = [string[]]@($table.Keys)
    [Array]::Sort($keys, [System.StringComparer]::Ordinal)

    $target = Join-Path $OutputDirectory "$($direction.Name).txt.gz"
    $stream = [System.IO.File]::Create($target)
    try {
        $gzip = [System.IO.Compression.GZipStream]::new(
            $stream, [System.IO.Compression.CompressionLevel]::SmallestSize)
        try {
            $writer = [System.IO.StreamWriter]::new($gzip, [System.Text.UTF8Encoding]::new($false))
            # WriteLine uses the platform newline. Pin it so the same tag gives
            # the same table on Windows, Linux, and macOS.
            $writer.NewLine = "`n"
            try {
                $writer.WriteLine("# OpenCC $OpenCcTag, Apache-2.0. Generated by scripts/New-ConversionData.ps1.")
                foreach ($key in $keys) {
                    $writer.Write($key)
                    $writer.Write("`t")
                    $writer.WriteLine($table[$key])
                }
            } finally { $writer.Dispose() }
        } finally { $gzip.Dispose() }
    } finally { $stream.Dispose() }

    Write-Host "Wrote $target ($($keys.Length) entries)"
}
